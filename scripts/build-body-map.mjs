// Writes src/data/bodyMap.ts, the body outlines Progress → Muscles draws, from MuscleMap by Melih Colpan
// (https://github.com/melihcolpan/MuscleMap, MIT License), which ships them as Swift source rather than .svg files.
// The male front and back, each muscle group's paths as they are; its sub-groups (upper chest, inner quad…), which
// lie over the groups they belong to, are left out. Run it with a checkout of MuscleMap:
//   node scripts/build-body-map.mjs path/to/MuscleMap
import fs from "node:fs";

const repo = process.argv[2];
if (!repo) {
  console.error("Usage: node scripts/build-body-map.mjs path/to/MuscleMap");
  process.exit(1);
}
const SUB = new Set(["upperChest", "lowerChest", "innerQuad", "outerQuad", "upperAbs", "lowerAbs", "frontDeltoid", "rearDeltoid", "upperTrapezius", "lowerTrapezius", "rotatorCuff", "rhomboids"]);

/** Each group's slug and paths, in the file's order. */
function parts(file) {
  const src = fs.readFileSync(`${repo}/Sources/MuscleMap/Data/${file}`, "utf8");
  return src
    .split("BodyPartPathData(")
    .slice(1)
    .map((chunk) => ({ slug: /slug:\s*\.(\w+)/.exec(chunk)?.[1], d: [...chunk.matchAll(/"(M[^"]+)"/g)].map((m) => m[1]) }))
    .filter((p) => p.slug && !SUB.has(p.slug) && p.d.length);
}
/** A view box from BodyPathData.swift's: its origin and size. */
function viewBox(name) {
  const src = fs.readFileSync(`${repo}/Sources/MuscleMap/Data/BodyPathData.swift`, "utf8");
  const m = new RegExp(`static let ${name} = BodyViewBox\\(\\s*origin: CGPoint\\(x: (\\d+), y: (\\d+)\\),\\s*size: CGSize\\(width: (\\d+), height: (\\d+)\\)`).exec(src);
  if (!m) throw new Error(`no view box ${name}`);
  return m.slice(1).join(" ");
}

const license = fs
  .readFileSync(`${repo}/LICENSE`, "utf8")
  .trim()
  .split("\n")
  .map((l) => ` * ${l}`.trimEnd())
  .join("\n");
const body = { front: { viewBox: viewBox("maleFront"), parts: parts("MaleFrontPaths.swift") }, back: { viewBox: viewBox("maleBack"), parts: parts("MaleBackPaths.swift") } };
const out = `/* Generated by scripts/build-body-map.mjs: don't edit by hand.
 *
 * The body outlines Progress → Muscles draws, from MuscleMap by Melih Colpan (https://github.com/melihcolpan/MuscleMap):
 * the male front and back, each muscle group's paths unchanged, its sub-groups left out. Used under the MIT License:
 *
${license}
 */

export interface BodyPart {
  /** MuscleMap's name for the group: chest, deltoids, upperBack… */
  slug: string;
  d: string[];
}
export interface BodySide {
  viewBox: string;
  parts: BodyPart[];
}

export const BODY: { front: BodySide; back: BodySide } = ${JSON.stringify(body)};
`;
fs.writeFileSync(new URL("../src/data/bodyMap.ts", import.meta.url), out);
console.log(`src/data/bodyMap.ts: ${body.front.parts.length} front and ${body.back.parts.length} back groups, ${Math.round(out.length / 1024)} KB`);
